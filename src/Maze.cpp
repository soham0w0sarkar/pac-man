Maze::Maze() {
  std::cout << "Creating maze...\n";
  createMaze();

  std::cout << "Rows: " << grid.size() << "\n";

  for (const auto &row : grid) {
    std::cout << "Columns: " << row.size() << "\n";
  }
}

